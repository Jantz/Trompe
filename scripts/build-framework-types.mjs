#!/usr/bin/env node
// Generates framework typings for every tr-* element from custom-elements.json:
//   dist/frameworks/props.d.ts   framework-neutral prop interfaces (TrButtonProps, ...) and event maps
//   dist/frameworks/react.d.ts   React 19 JSX.IntrinsicElements
//   dist/frameworks/vue.d.ts     Vue 3 GlobalComponents (Volar / vue-tsc)
//   dist/frameworks/svelte.d.ts  Svelte 5 SvelteHTMLElements (svelte/elements)
// plus an empty .js next to each, so `import 'trompe/frameworks/react'` also works at runtime.
//
// Only what the manifest states is typed: attributes (by attribute name, and by property name when
// it differs), public writable properties, and documented events. Anything whose type text is not
// a plain literal union or primitive falls back to string.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'dist/frameworks');
mkdirSync(outDir, { recursive: true });
const manifest = JSON.parse(readFileSync(resolve(root, 'custom-elements.json'), 'utf8'));

const elements = manifest.modules
  .flatMap((m) => (m.declarations ?? []).map((d) => ({ ...d, modulePath: m.path })))
  .filter((d) => d.customElement && d.tagName)
  .sort((a, b) => a.tagName.localeCompare(b.tagName));

const PRIMITIVES = new Set(['string', 'number', 'boolean']);
/** Turns a manifest type text into a safe TS type, without undefined/null. */
function tsType(text) {
  if (!text) return 'string';
  const parts = text.split('|').map((p) => p.trim()).filter((p) => p && p !== 'undefined' && p !== 'null');
  const ok = parts.every((p) => PRIMITIVES.has(p) || /^'[^'\\]*'$/.test(p) || /^"[^"\\]*"$/.test(p) || /^-?\d+(\.\d+)?$/.test(p));
  return ok && parts.length ? parts.join(' | ') : 'string';
}
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);
const doc = (text, indent = '  ') => {
  const t = (text ?? '').trim();
  if (!t) return '';
  return `${indent}/** ${t.replace(/\*\//g, '* /').replace(/\n\s*/g, `\n${indent} * `)} */\n`;
};
const pascal = (tag) => tag.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const isPublic = (m) => !m.privacy || m.privacy === 'public';

/** Event type text: keep (Custom)Event types from the manifest, otherwise Event. */
const eventType = (e) => (/^(Custom)?Event(<.*>)?$/.test(e.type?.text ?? '') ? e.type.text : 'Event');

function propsOf(el) {
  const props = new Map();
  const add = (name, type, description) => {
    if (!props.has(name)) props.set(name, { type, description });
  };
  for (const a of el.attributes ?? []) {
    const t = tsType(a.type?.text);
    // A name that is also a property (value, min, ...) is set as a property, so it takes the
    // property's own type. A name that exists only as an attribute (hide-value) is set with
    // setAttribute, so a numeric one may also be given as a string.
    const attributeOnly = !a.fieldName || a.fieldName !== a.name;
    add(a.name, attributeOnly && /\bnumber\b/.test(t) ? `${t} | string` : t, a.description);
    if (a.fieldName && a.fieldName !== a.name) add(a.fieldName, t, a.description);
  }
  for (const m of el.members ?? []) {
    if (m.kind !== 'field' || !isPublic(m) || m.static || m.readonly || m.name.startsWith('_')) continue;
    add(m.name, tsType(m.type?.text), m.description);
  }
  return props;
}

const header = (what) => `// Generated by scripts/build-framework-types.mjs from custom-elements.json. Do not edit.
// ${what}
`;

// ---------- props.d.ts ----------
let propsDts = header('Framework-neutral prop and event types for every Trompe element.');
const imports = elements.map((el) => {
  const rel = relative('dist/frameworks', el.modulePath).replace(/\\/g, '/');
  const mod = rel.startsWith('.') ? rel : `./${rel}`;
  return `import type { ${el.name} } from '${mod}';`;
});
propsDts += `${imports.join('\n')}\n\n`;
propsDts += `export type { ${elements.map((e) => e.name).join(', ')} };\n\n`;
for (const el of elements) {
  const props = propsOf(el);
  propsDts += doc(`Props of <${el.tagName}>${el.summary ? `: ${el.summary}` : ''}`, '');
  propsDts += `export interface ${pascal(el.tagName)}Props {\n`;
  for (const [name, p] of props) propsDts += `${doc(p.description)}  ${key(name)}?: ${p.type};\n`;
  propsDts += `}\n\n`;
  propsDts += doc(`Events <${el.tagName}> documents.`, '');
  propsDts += `export interface ${pascal(el.tagName)}Events {\n`;
  for (const e of el.events ?? []) propsDts += `${doc(e.description)}  ${key(e.name)}: ${eventType(e)};\n`;
  propsDts += `}\n\n`;
}
propsDts += `/** Every Trompe element: tag -> { element, props, events, role }. */
export interface TrompeElements {
${elements
  .map((el) => `  '${el.tagName}': { element: ${el.name}; props: ${pascal(el.tagName)}Props; events: ${pascal(el.tagName)}Events; role: ${el.role ? `'${el.role}'` : 'null'} };`)
  .join('\n')}
}
`;

// Event names each framework already types on every element; others get explicit handlers.
const STANDARD_EVENTS = new Set(['click', 'input', 'change', 'focus', 'blur', 'keydown', 'keyup', 'pointerdown', 'pointerup']);
const customEvents = (el) => (el.events ?? []).filter((e) => !STANDARD_EVENTS.has(e.name));
const elDoc = (el) => doc(`${el.summary ?? `<${el.tagName}>`}${el.role ? `\n\nARIA role: ${el.role}.` : ''}`, '      ');

// ---------- react.d.ts ----------
let react = header(`React 19: typed JSX for tr-* elements. Add once: import type {} from 'trompe/frameworks/react';
// React 19 sets a prop as a DOM property when the element has it (value={50}), otherwise as an
// attribute; onInput / onChange / onClick receive the elements' native bubbling events.`);
react += `import type * as React from 'react';
import type * as P from './props.js';

/** Base props React accepts on any element, minus names Trompe defines itself. */
type Base<E extends HTMLElement, Own> = Omit<React.DetailedHTMLProps<React.HTMLAttributes<E>, E>, keyof Own> & {
  /** Plain class attribute (React 19 also accepts className on custom elements). */
  class?: string;
};

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements {
${elements
  .map((el) => {
    const P_ = `P.${pascal(el.tagName)}Props`;
    const extra = customEvents(el).map((e) => `'on${e.name}'?: (event: ${eventType(e)}) => void`);
    const own = extra.length ? `${P_} & { ${extra.join('; ')} }` : P_;
    return `${elDoc(el)}      '${el.tagName}': Base<P.${el.name}, ${own}> & ${own};`;
  })
  .join('\n')}
    }
  }
}
`;

// ---------- vue.d.ts ----------
let vue = header(`Vue 3: typed templates (Volar / vue-tsc) for tr-* elements. Add once: import type {} from 'trompe/frameworks/vue';
// Also tell the Vue compiler they are custom elements: compilerOptions.isCustomElement = (tag) => tag.startsWith('tr-').`);
vue += `import type { DefineComponent, HTMLAttributes } from 'vue';
import type * as P from './props.js';

type Handlers<Ev> = { [K in keyof Ev as \`on\${Capitalize<K & string>}\`]?: (event: Ev[K]) => void };
type El<Own, Ev> = DefineComponent<Own & Handlers<Ev> & Omit<HTMLAttributes, keyof Own | keyof Handlers<Ev>>>;

declare module 'vue' {
  interface GlobalComponents {
${elements.map((el) => `${elDoc(el).replace(/^ {6}/gm, '    ')}    '${el.tagName}': El<P.${pascal(el.tagName)}Props, P.${pascal(el.tagName)}Events>;`).join('\n')}
  }
}
`;

// ---------- svelte.d.ts ----------
let svelte = header(`Svelte 5: typed markup for tr-* elements. Add once (e.g. in src/app.d.ts or main.ts): import type {} from 'trompe/frameworks/svelte';
// Svelte sets a prop as a DOM property when the element has it, otherwise as an attribute;
// oninput / onchange / onclick receive the elements' native events.`);
svelte += `import type { HTMLAttributes } from 'svelte/elements';
import type * as P from './props.js';

type El<E extends HTMLElement, Own> = Omit<HTMLAttributes<E>, keyof Own> & Own;

declare module 'svelte/elements' {
  interface SvelteHTMLElements {
${elements
  .map((el) => {
    const P_ = `P.${pascal(el.tagName)}Props`;
    const extra = customEvents(el).map((e) => `'on${e.name}'?: (event: ${eventType(e)} & { currentTarget: P.${el.name} }) => void`);
    const own = extra.length ? `${P_} & { ${extra.join('; ')} }` : P_;
    return `${elDoc(el).replace(/^ {6}/gm, '    ')}    '${el.tagName}': El<P.${el.name}, ${own}>;`;
  })
  .join('\n')}
  }
}
`;

const files = { 'props.d.ts': propsDts, 'react.d.ts': react, 'vue.d.ts': vue, 'svelte.d.ts': svelte };
for (const [name, text] of Object.entries(files)) writeFileSync(resolve(outDir, name), text);
for (const name of ['react', 'vue', 'svelte']) writeFileSync(resolve(outDir, `${name}.js`), '// Types only: see the .d.ts next to this file.\nexport {};\n');
console.log(`frameworks: ${elements.length} elements -> dist/frameworks/{props,react,vue,svelte}.d.ts`);
